import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import SwaggerParser from '@apidevtools/swagger-parser';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const openapiUrl = new URL('../contracts/v1/openapi.yaml', import.meta.url);
const eventSchemaUrl = new URL('../contracts/v1/room-events.schema.json', import.meta.url);
const generatedUrl = new URL('../contracts/v1/generated/api.ts', import.meta.url);
const generatedEventUrl = new URL('../contracts/v1/generated/room-events.ts', import.meta.url);

await SwaggerParser.validate(fileURLToPath(openapiUrl));

const eventSchema = JSON.parse(await readFile(eventSchemaUrl, 'utf8'));
const ajv = new Ajv2020({ strict: true });
addFormats(ajv);
ajv.compile(eventSchema);

const generatedHeader = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;
const expected = generatedHeader + astToString(await openapiTS(openapiUrl));
const committed = await readFile(generatedUrl, 'utf8');
assert.equal(
  committed,
  expected,
  '生成的 TypeScript 类型已漂移；请运行 npm run contracts:generate 后提交结果。',
);

const expectedEvent = await compile(eventSchema, 'RoomInvalidationEvent', {
  bannerComment: '/* 由 room-events.schema.json 自动生成；请勿直接修改。 */',
  style: { singleQuote: true },
});
assert.equal(
  await readFile(generatedEventUrl, 'utf8'),
  expectedEvent,
  '生成的房间失效通知 TypeScript 类型已漂移；请运行 npm run contracts:generate 后提交结果。',
);

const tests = spawnSync(process.execPath, ['--test'], { stdio: 'inherit' });
if (tests.error) throw tests.error;
if (tests.status !== 0) process.exit(tests.status ?? 1);

console.log('合同解析、语义测试与 TypeScript 漂移检查通过。');
